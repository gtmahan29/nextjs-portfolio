const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ts = require('typescript');
const source = fs.readFileSync('components/journey/showroom-scroll.ts', 'utf8');
const context = { exports: {}, window: { innerHeight: 1000 } };
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, context);
const { ShowroomScrollGate } = context.exports;
const stops = { start: 5000, end: 6200, step: 600 };
const gate = new ShowroomScrollGate();
assert.equal(gate.decide(stops, 4700, 4000, 0, true), 5000, 'long incoming wheel lands on first slide');
for (let t=50;t<1400;t+=50) assert.equal(gate.decide(stops,5000,4000,t,false),'hold','momentum cannot advance');
assert.equal(gate.decide(stops,5000,4000,1700,true),5600,'new gesture advances exactly one slide');
assert.equal(gate.decide(stops,5600,4000,1900,true),'hold','camera must settle before another gesture');
assert.equal(gate.decide(stops,5600,4000,2900,true),6200,'new gesture lands exactly on last slide');
assert.equal(gate.decide(stops,6200,4000,3200,false),'hold','same gesture cannot exit');
assert.equal(gate.decide(stops,6200,4000,4000,true),7200,'separate gesture exits forward');
assert.equal(gate.decide(stops,7200,-4000,5300,true),6200,'reverse entry lands on last slide');
assert.equal(gate.decide(stops,6200,-4000,5400,false),'hold','reverse entry momentum cannot advance');
assert.equal(gate.decide(stops,6200,-4000,6500,true),5600,'reverse new gesture advances one slide');
assert.equal(gate.decide(stops,5600,-4000,7700,true),5000,'reverse lands on first slide');
assert.equal(gate.decide(stops,5000,-4000,7800,false),'hold','first-slide exit requires new gesture');
assert.equal(gate.decide(stops,5000,-4000,9000,true),4000,'separate reverse gesture exits');
const outside = new ShowroomScrollGate();
assert.equal(outside.decide(stops,2000,20,0,true),null,'ordinary outside scrolling remains native to Lenis');
assert.equal(outside.decide(null,5000,500,0,true),null,'other pages have no showroom interception');
const touch = new ShowroomScrollGate();
touch.begin(0); assert.equal(touch.decide(stops,5000,40,30,false),5600,'one swipe advances');
assert.equal(touch.decide(stops,5600,40,1300,false),'hold','long held swipe remains one gesture');
touch.begin(1500); assert.equal(touch.decide(stops,5600,40,1530,false),6200,'new swipe advances');
console.log('Passed: long-wheel entry, momentum, three stops, separate exits, reverse travel, touch and outside scrolling.');
